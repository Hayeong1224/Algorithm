-- ITEM_A(PARENT) -> ITEM_B, PARENT X -> ROOT

SELECT A.ITEM_ID, A.ITEM_NAME, A.RARITY 
FROM ITEM_INFO A
# WHERE A.ITEM_ID NOT IN (
#     SELECT DISTINCT PARENT_ITEM_ID
#     FROM ITEM_TREE B
#     WHERE PARENT_ITEM_ID IS NOT NULL -- 이거 안 붙이면 NULL도 집계돼서 UNKNOWN이 됨
# ) 
WHERE NOT EXISTS (
    SELECT 1
    FROM ITEM_TREE B
    WHERE A.ITEM_ID = B.PARENT_ITEM_ID
) 

ORDER BY A.ITEM_ID DESC